from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .evidence import evidence_as_prompt, select_evidence
from .llm_client import call_openai_json, render_prompt


def run_model_spec(
    *,
    target: dict[str, Any],
    text_json: dict[str, Any],
    schema_path: str | Path,
    prompt_path: str | Path,
    offline: bool = False,
) -> dict[str, Any]:
    if offline:
        return offline_model_spec(target)
    schema = json.loads(Path(schema_path).read_text(encoding="utf-8"))
    metadata = json.dumps(target, ensure_ascii=False, indent=2)
    prompt = render_prompt(
        prompt_path,
        metadata=metadata,
        evidence=evidence_as_prompt(select_evidence(text_json), max_chars=16000),
    )
    return call_openai_json(prompt=prompt, schema=schema, schema_name="model_spec")


