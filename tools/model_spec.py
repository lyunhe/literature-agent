def model_spec_to_markdown(spec: dict[str, Any]) -> str:
    lines = ["# Model Spec", ""]
    for key in ["sets", "parameters", "variables", "constraints", "uncertainty", "implementation_notes"]:
        title = key.replace("_", " ").title()
        lines += [f"## {title}", ""]
        lines += [f"- {item}" for item in spec.get(key, [])]
        lines.append("")
    lines += ["## Objective", "", spec.get("objective", ""), ""]
    return "\n".join(lines)

